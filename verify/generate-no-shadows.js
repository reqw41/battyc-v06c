'use strict';
// Offline mask conversion. Keep lit details, their one-pixel black outline,
// and enclosed dark interiors. Remove external black-only drop shadows.
const fs=require('fs'),assert=require('assert');
function stripShadow(data){
 const [w,h]=data,W=w*8,lit=new Uint8Array(W*h),keep=new Uint8Array(W*h);
 for(let y=0;y<h;y++)for(let x=0;x<W;x++){const at=2+2*(y*w+(x>>3)),bit=128>>(x&7);lit[y*W+x]=!!(data[at]&data[at+1]&bit);}
 for(let y=0;y<h;y++)for(let x=0;x<W;x++)if(lit[y*W+x])for(let dy=-1;dy<=1;dy++)for(let dx=-1;dx<=1;dx++){const nx=x+dx,ny=y+dy;if(nx>=0&&nx<W&&ny>=0&&ny<h)keep[ny*W+nx]=1;}
 // Flood the exterior of the outlined lit silhouette; enclosed dark details
 // belong to the object. Four-neighbour flood preserves diagonal outlines.
 const outside=new Uint8Array(W*h),queue=[];
 function add(x,y){const i=y*W+x;if(!keep[i]&&!outside[i]){outside[i]=1;queue.push(i);}}
 for(let x=0;x<W;x++){add(x,0);add(x,h-1);}for(let y=0;y<h;y++){add(0,y);add(W-1,y);}
 for(let n=0;n<queue.length;n++){const i=queue[n],x=i%W,y=Math.floor(i/W);if(x)add(x-1,y);if(x+1<W)add(x+1,y);if(y)add(x,y-1);if(y+1<h)add(x,y+1);}
 const mask=new Uint8Array(w*h);let lastX=0,lastY=0,removed=0;
 for(let y=0;y<h;y++)for(let x=0;x<W;x++){const at=2+2*(y*w+(x>>3)),bit=128>>(x&7);if(!(data[at]&bit))continue;if(outside[y*W+x]){assert(!lit[y*W+x]);removed++;continue;}mask[y*w+(x>>3)]|=bit;lastX=Math.max(lastX,x);lastY=Math.max(lastY,y);}
 const nw=(lastX>>3)+1,nh=lastY+1,out=[nw,nh];
 for(let y=0;y<nh;y++)for(let x=0;x<nw;x++){const m=mask[y*w+x];out.push(m,data[2+2*(y*w+x)+1]&m);}
 return {data:out,removed,before:[w,h],after:[nw,nh]};
}
function shifted(data,phase){
 const [w,h]=data,out=[w+1,h];
 for(let y=0;y<h;y++){const row=new Uint8Array(2*(w+1));for(let x=0;x<w;x++)for(let p=0;p<2;p++){const b=data[2+2*(y*w+x)+p];row[2*x+p]|=b>>>phase;row[2*(x+1)+p]|=(b<<(8-phase))&255;}out.push(...row);}return out;
}
function generate(){
 const input='gfx/sprites_with_masks_2.asm',text=fs.readFileSync(input,'utf8');
 const blocks=[...text.matchAll(/^(spr_\w+):([\s\S]*?)(?=^spr_\w+:|$(?![\s\S]))/gm)].map(m=>{
  const data=[];for(const line of m[2].split('\n')){const p=line.split(';')[0].match(/^\s*DEFB\s+(.+)/i);if(p)for(const value of p[1].split(',')){assert(/^\s*\$[\da-f]+\s*$/i.test(value),value);data.push(parseInt(value.trim().slice(1),16));}}
  return {name:m[1],data};
 });
 assert(blocks.length>40,'sprite source parse');
 const byName=Object.fromEntries(blocks.map(b=>[b.name,b])),stats=[];
 for(const b of blocks){
  // Explosion fragments, symbols, UFO and bonus artwork are not drop shadows.
  // In particular, the last bullet explosion frame is deliberately all black.
  if(!b.data[0]||!b.data[1]||!/^spr_(bomb$|big_ball$|ball_normal$|bat_|spark_|bird_|bullet_[12]$)/.test(b.name))continue;
  const expected=2+2*b.data[0]*b.data[1];
  // Original bird frame 4 claims 15 rows but stores 14. Its extra row reads
  // and inverts the next frame's header. Treat missing source bytes as zero.
  assert(b.data.length===expected||(b.name==='spr_bird_4'&&expected-b.data.length===6),b.name);
  const source=b.data.slice();
  // The bullet's last three checkerboard rows are a lit/dark drop shadow,
  // unlike the black-only shadows on the other selected sprites.
  if(/^spr_bullet_[12]$/.test(b.name)){source[1]=5;source.length=12;}
  const result=stripShadow(source);b.converted=result.data;stats.push({name:b.name,...result,data:undefined,before:b.data.slice(0,2)});
 }
 const phases=Array.from({length:7},(_,i)=>['spr_ball_normal','spr_ball_normal_shift_'+(i+1),i+1]);
 phases.push(['spr_bat_normal','spr_bat_normal_shift',4],['spr_bat_big','spr_bat_big_shift',4],['spr_bat_gun','spr_bat_gun_shift',4]);
 for(const [src,dst,phase]of phases){byName[dst].converted=shifted(byName[src].converted,phase);stats.push({name:dst,generatedFrom:src,phase,after:byName[dst].converted.slice(0,2)});}
 let output='; Generated by node verify/generate-no-shadows.js. Do not edit.\n; Original allocations retained; compact payload then zero padding.\n';
 for(const b of blocks){const data=b.converted||b.data;assert(data.length<=b.data.length,b.name+' exceeds original allocation');output+=b.name+':\n';for(let i=0;i<data.length;i+=12)output+='  DEFB '+data.slice(i,i+12).map(v=>'$'+v.toString(16).padStart(2,'0')).join(',')+'\n';if(data.length<b.data.length)output+='  DS '+(b.data.length-data.length)+',0\n';}
 fs.writeFileSync('gfx/sprites_no_shadows_2.asm',output);
 fs.writeFileSync('outputs/batty-no-shadows-assets.json',JSON.stringify({method:'Lit pixels + 1px black outline + enclosed dark interiors; remove exterior black-only pixels; trim right/bottom bounds; keep original allocations and collision boxes; shifted ball/paddle phases generated offline',stats},null,2));
 console.log(stats.filter(s=>s.removed));
}
if(require.main===module)generate();
module.exports={stripShadow,shifted};
