'use strict';
// ZX Spectrum field frame (pipes and connectors) as 1-bpp cells plus per-material colour masks.
// Source: the original border sprites, verify/fixtures/zx/frame_sprites.asm (cell-major bytes).
const fs=require('fs');
const text=fs.readFileSync('verify/fixtures/zx/frame_sprites.asm','utf8').replace(/;.*/g,'');
const spr={};let cur=null;
for(const m of text.matchAll(/^(spr_\w+):|DEFB\s+(.+)/gm)){if(m[1]){cur=m[1];spr[cur]=[];}else spr[cur].push(...m[2].split(',').map(v=>v.trim()));}
const num=v=>parseInt(v.replace('$',''),16),pix=(n,part)=>{const b=spr[n];let i=0;for(let p=0;;p++){const w=num(b[i]),h=num(b[i+1]),data=b.slice(i+2,i+2+w*h).map(num);i+=2+w*h;i+=2+num(b[i])*num(b[i+1]);if(p===part)return data;}};
const rev=v=>{let r=0;for(let i=0;i<8;i++)if(v&(1<<i))r|=128>>i;return r;};
// Top band, left half: edge, thin, bold (4 cells x 8 rows each); the right half is its mirror image.
const top=[...pix('spr_bord_horiz_left_edge',0),...pix('spr_bord_horiz_left_thin',0),...pix('spr_bord_horiz_left_bold',0)];
const order=[0,1,2,1],leftCells=order.flatMap(p=>[0,1,2,3].map(c=>p*4+c));
const right=['right_thin','right_bold','right_thin','right_edge'].flatMap(n=>pix('spr_bord_horiz_'+n,0));
for(let c=0;c<16;c++)for(let r=0;r<8;r++){const want=right[c*8+r],got=rev(top[leftCells[15-c]*8+r]);if(want!==got)throw Error('top is not a mirror image at cell '+c+' row '+r);}
// Side wall, left: the paddle-like piece (32 rows) and the pipe piece (24 rows); the right wall is the mirror.
const side=[...pix('spr_bord_left_bold',0),...pix('spr_bord_left_thin',0)];
const sideRight=[...pix('spr_bord_left_bold',1),...pix('spr_bord_left_thin',1)];
side.forEach((v,i)=>{if(rev(v)!==sideRight[i])throw Error('side is not a mirror image at '+i);});
// Materials: 0 tube, 1 connector, 2 cap. Colours come from two masks per material:
// plane A = bits & maskA, plane C = bits & maskC, plane E = ~bits | maskC,
// so a set bit is white (no mask), grey (C only) or cyan (A and C); a clear bit is the HUD paper.
// Top band: the masks are row patterns (bit 7 = top row). Side walls: plain bit masks, light from the left.
const T=0,C=1,K=2;
const topSeq=leftCells.map((cell,i)=>cell*4+((i&3)===3?K:(order[i>>2]===1?C:T)));
const sideSeq=[K,T,T,K,C,C,C];
const topMasks=[[0x3e,0x3f],[0x00,0x3f],[0x0f,0x0f]],sideMasks=[[0x1c,0x1f],[0x00,0x0f],[0x0f,0x0f]];
const db=a=>{let s='';for(let i=0;i<a.length;i+=8)s+=' DEFB '+a.slice(i,i+8).map(v=>'$'+v.toString(16).padStart(2,'0')).join(',')+'\n';return s;};
fs.writeFileSync('gfx/zx_frame.asm','; Generated by verify/generate-zx-frame.js: ZX field frame, one bit per pixel.\n'+
 'ZxFrameTop:\n'+db(top)+'ZxFrameTopSeq: ; bitmap cell*4 + material, left half of the top band\n'+db(topSeq)+
 'ZxFrameSide:\n'+db(side)+'ZxFrameSideSeq:\n'+db(sideSeq)+
 'ZxFrameTopMasks: ; row patterns A,C for tube, connector, cap\n'+db(topMasks.flat())+'ZxFrameSideMasks: ; bit masks A,C\n'+db(sideMasks.flat()));
module.exports={top,side,topSeq,sideSeq,topMasks,sideMasks,rev};
